package releasemanifest

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"strings"
	"time"
)

const (
	// DefaultZuulJob is the Zuul job that generates the release manifest a
	// buildset tests.
	DefaultZuulJob = "atmosphere-release-manifest"
	// DefaultZuulArtifact is the name of the Zuul artifact holding it.
	DefaultZuulArtifact = "Release manifest"

	// AnnotationTested records whether a published manifest is the one
	// tested in CI. It is only set on manifests that were not.
	AnnotationTested = "com.vexxhost.atmosphere.tested"

	maxManifestSize = 4 << 20
)

// ErrNoTestedManifest means no successful buildset tested a manifest for the
// change.
var ErrNoTestedManifest = errors.New("no tested release manifest found")

// ZuulLookup finds the release manifest that Zuul tested for a change.
type ZuulLookup struct {
	// API is the Zuul tenant API, e.g. https://zuul.example.com/api/tenant/oss.
	API      string
	Project  string
	Change   string
	Patchset string
	// Pipelines are searched in order, e.g. gate before check.
	Pipelines []string
	Job       string
	Artifact  string
	Client    *http.Client
}

// Tested is a release manifest that a Zuul buildset tested.
type Tested struct {
	Manifest *Manifest
	Pipeline string
	Buildset string
	URL      string
}

type zuulBuild struct {
	UUID      string `json:"uuid"`
	Result    string `json:"result"`
	Artifacts []struct {
		Name string `json:"name"`
		URL  string `json:"url"`
	} `json:"artifacts"`
	Buildset struct {
		UUID string `json:"uuid"`
	} `json:"buildset"`
}

func (l ZuulLookup) client() *http.Client {
	if l.Client != nil {
		return l.Client
	}
	return &http.Client{Timeout: 60 * time.Second}
}

func (l ZuulLookup) get(ctx context.Context, rawURL string, limit int64) ([]byte, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, rawURL, nil)
	if err != nil {
		return nil, err
	}
	resp, err := l.client().Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("GET %s: HTTP %d", rawURL, resp.StatusCode)
	}
	data, err := io.ReadAll(io.LimitReader(resp.Body, limit+1))
	if err != nil {
		return nil, err
	}
	if int64(len(data)) > limit {
		return nil, fmt.Errorf("GET %s: response larger than %d bytes", rawURL, limit)
	}
	return data, nil
}

func (l ZuulLookup) getJSON(ctx context.Context, path string, query url.Values, v interface{}) error {
	u := strings.TrimSuffix(l.API, "/") + path
	if len(query) > 0 {
		u += "?" + query.Encode()
	}
	data, err := l.get(ctx, u, maxManifestSize)
	if err != nil {
		return err
	}
	return json.Unmarshal(data, v)
}

// Find returns the manifest generated by the newest buildset that tested the
// change's patchset and in which every job succeeded.
func (l ZuulLookup) Find(ctx context.Context) (*Tested, error) {
	if l.API == "" || l.Project == "" || l.Change == "" || l.Patchset == "" {
		return nil, fmt.Errorf("zuul lookup needs an API, project, change and patchset")
	}
	job, artifact := l.Job, l.Artifact
	if job == "" {
		job = DefaultZuulJob
	}
	if artifact == "" {
		artifact = DefaultZuulArtifact
	}

	for _, pipeline := range l.Pipelines {
		var builds []zuulBuild
		err := l.getJSON(ctx, "/builds", url.Values{
			"project":  {l.Project},
			"change":   {l.Change},
			"patchset": {l.Patchset},
			"pipeline": {pipeline},
			"job_name": {job},
			"result":   {"SUCCESS"},
			"limit":    {"20"},
		}, &builds)
		if err != nil {
			return nil, err
		}

		for _, build := range builds {
			var buildset struct {
				Result string `json:"result"`
			}
			if err := l.getJSON(ctx, "/buildset/"+build.Buildset.UUID, nil, &buildset); err != nil {
				return nil, err
			}
			if buildset.Result != "SUCCESS" {
				continue
			}

			for _, a := range build.Artifacts {
				if a.Name != artifact {
					continue
				}
				data, err := l.get(ctx, a.URL, maxManifestSize)
				if err != nil {
					return nil, err
				}
				m, err := Unmarshal(data)
				if err != nil {
					return nil, fmt.Errorf("%s: %w", a.URL, err)
				}
				return &Tested{Manifest: m, Pipeline: pipeline, Buildset: build.Buildset.UUID, URL: a.URL}, nil
			}
		}
	}

	return nil, ErrNoTestedManifest
}

// PublishDecision is the manifest to publish and why.
type PublishDecision struct {
	Manifest *Manifest
	Tested   *Tested
	Reason   string
	Options  PushOptions
}

// DecidePublish chooses the tested manifest when it was generated from the
// same image inputs as the commit being published, and the fallback manifest
// otherwise. A fallback manifest is annotated as untested.
func DecidePublish(ctx context.Context, lookup *ZuulLookup, inputs string, fallback *Manifest, opts PushOptions) (*PublishDecision, error) {
	untested := func(reason string) *PublishDecision {
		o := opts
		o.Annotations = map[string]string{AnnotationTested: "false"}
		for k, v := range opts.Annotations {
			o.Annotations[k] = v
		}
		return &PublishDecision{Manifest: fallback, Reason: reason, Options: o}
	}

	if lookup == nil {
		return untested("no change to look up"), nil
	}

	tested, err := lookup.Find(ctx)
	switch {
	case errors.Is(err, ErrNoTestedManifest):
		return untested(fmt.Sprintf("no successful buildset tested change %s at %s", lookup.Change, lookup.Patchset)), nil
	case err != nil:
		return untested(fmt.Sprintf("looking up the tested manifest failed: %v", err)), nil
	case tested.Manifest.Inputs == "":
		return untested("the tested manifest does not record its image inputs"), nil
	case tested.Manifest.Inputs != inputs:
		return untested(fmt.Sprintf("image inputs changed since buildset %s tested the change (%s, now %s)",
			tested.Buildset, tested.Manifest.Inputs, inputs)), nil
	}

	return &PublishDecision{
		Manifest: tested.Manifest,
		Tested:   tested,
		Reason:   fmt.Sprintf("tested in %s buildset %s", tested.Pipeline, tested.Buildset),
		Options:  opts,
	}, nil
}
